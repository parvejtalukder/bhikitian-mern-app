/**
 * Local mock MediaWiki API for load and failure testing.
 *
 *   node loadtest/mock-mediawiki.mjs                 # healthy, ~8ms latency
 *   MOCK_MODE=fail node loadtest/mock-mediawiki.mjs  # upstream outage (HTTP 503)
 *   MOCK_MODE=slow MOCK_LATENCY_MS=2000 node loadtest/mock-mediawiki.mjs
 *   MOCK_MODE=flap node loadtest/mock-mediawiki.mjs  # alternating failure
 *   MOCK_FAIL_RATE=0.2 node loadtest/mock-mediawiki.mjs
 *
 * Point the app at it with MEDIAWIKI_BASE_URL=http://127.0.0.1:4599 — never send
 * high-volume traffic to the real wiki.
 *
 * Control/support endpoints:
 *   GET  /_mock/stats                -> request counters (ground truth for
 *                                       "how many requests reached upstream")
 *   POST /_mock/mode  {mode,latencyMs,failRate}
 *   POST /_mock/reset
 */
import http from 'node:http';

const PORT = Number(process.env.MOCK_PORT || 4599);
let mode = process.env.MOCK_MODE || 'ok';
let latencyMs = Number(process.env.MOCK_LATENCY_MS || 8);
let failRate = Number(process.env.MOCK_FAIL_RATE || 0);

const stats = {
  startedAt: new Date().toISOString(),
  apiRequests: 0,
  byAction: {},
  byStatus: {},
  controlRequests: 0,
  tombstoned: 0,
};
let flapTick = 0;
/** Titles "deleted" at runtime: parse returns missingtitle, like a real delete. */
const tombstoned = new Set();

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function hash(text) {
  let h = 0;
  for (let i = 0; i < text.length; i += 1) h = (h * 31 + text.charCodeAt(i)) % 100000;
  return h;
}

function json(res, status, payload) {
  const body = JSON.stringify(payload);
  stats.byStatus[status] = (stats.byStatus[status] || 0) + 1;
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Content-Length': Buffer.byteLength(body),
  });
  res.end(body);
}

function shouldFail() {
  if (mode === 'fail') return true;
  if (mode === 'flap') {
    flapTick += 1;
    return flapTick % 2 === 0;
  }
  if (failRate > 0 && Math.random() < failRate) return true;
  return false;
}

function parsePayload(page) {
  const title = page;
  const id = 1000 + hash(title);
  return {
    parse: {
      title,
      pageid: id,
      revid: 500000 + id,
      displaytitle: title,
      text:
        `<div class="mw-parser-output"><p><b>${title}</b> is a synthetic encyclopedia article ` +
        'generated by the load-test mock so high-volume testing never touches the live wiki.</p>' +
        '<h2><span class="mw-headline" id="History">History</span></h2>' +
        `<p>Section body for ${title}. ${'Lorem ipsum dolor sit amet. '.repeat(20)}</p>` +
        '<h2><span class="mw-headline" id="References">References</span></h2><p></p></div>',
      sections: [
        { index: '1', level: '2', line: 'History', number: '1', anchor: 'History' },
        { index: '2', level: '2', line: 'References', number: '2', anchor: 'References' },
      ],
      categories: [{ category: 'Mock_articles' }],
      langlinks: [],
      redirects: [],
    },
  };
}

function searchPayload(query, limit) {
  return {
    query: {
      search: Array.from({ length: Number(limit) || 5 }, (_, index) => ({
        pageid: 2000 + index,
        title: `${query} result ${index + 1}`,
        snippet: `<span class="searchmatch">${query}</span> synthetic snippet ${index + 1}`,
        wordcount: 100 + index,
        timestamp: '2026-01-01T00:00:00Z',
      })),
    },
  };
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url || '/', `http://127.0.0.1:${PORT}`);

  if (url.pathname.startsWith('/_mock')) {
    stats.controlRequests += 1;
    if (req.method === 'POST' && url.pathname === '/_mock/mode') {
      const chunks = [];
      for await (const chunk of req) chunks.push(chunk);
      try {
        const body = JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}');
        if (body.mode) mode = String(body.mode);
        if (body.latencyMs !== undefined) latencyMs = Number(body.latencyMs);
        if (body.failRate !== undefined) failRate = Number(body.failRate);
        flapTick = 0;
      } catch {
        /* ignore malformed control payloads */
      }
      return json(res, 200, { mode, latencyMs, failRate });
    }
    if (req.method === 'POST' && url.pathname === '/_mock/reset') {
      stats.apiRequests = 0;
      stats.byAction = {};
      stats.byStatus = {};
      tombstoned.clear();
      stats.tombstoned = 0;
      return json(res, 200, { ok: true });
    }
    if (req.method === 'POST' && url.pathname === '/_mock/tombstone') {
      const chunks = [];
      for await (const chunk of req) chunks.push(chunk);
      try {
        const body = JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}');
        if (body.title) {
          tombstoned.add(String(body.title));
          stats.tombstoned = tombstoned.size;
        }
      } catch {
        /* ignore malformed control payloads */
      }
      return json(res, 200, { tombstoned: [...tombstoned] });
    }
    return json(res, 200, { mode, latencyMs, failRate, ...stats, tombstoned: [...tombstoned] });
  }

  if (url.pathname !== '/api.php') return json(res, 404, { error: 'not found' });

  const action = url.searchParams.get('action') || 'unknown';
  const list = url.searchParams.get('list');
  const meta = url.searchParams.get('meta');
  const key = meta ? `${action}:${meta}` : list ? `${action}:${list}` : action;

  stats.apiRequests += 1;
  stats.byAction[key] = (stats.byAction[key] || 0) + 1;

  if (latencyMs > 0) await sleep(latencyMs);

  if (shouldFail()) {
    stats.byStatus[503] = (stats.byStatus[503] || 0) + 1;
    res.writeHead(503, { 'Content-Type': 'text/plain' });
    res.end('mock upstream outage');
    return;
  }

  if (action === 'parse') {
    const page = url.searchParams.get('page') || 'Main Page';
    // A genuine MediaWiki 404 is HTTP 200 + an error object. Titles the control
    // endpoint "deleted" behave exactly like a real deletion.
    if (tombstoned.has(page) || /^(Missing|Does Not Exist|Load Test Missing)/i.test(page)) {
      return json(res, 200, {
        error: { code: 'missingtitle', info: "The page you specified doesn't exist." },
      });
    }
    return json(res, 200, parsePayload(page));
  }
  if (list === 'search') {
    return json(res, 200, searchPayload(url.searchParams.get('srsearch') || 'query', url.searchParams.get('srlimit')));
  }
  if (meta === 'siteinfo') {
    return json(res, 200, {
      query: {
        general: {
          sitename: 'Bhikitia (mock)',
          generator: 'MediaWiki 1.44.0',
          logo: '',
          lang: 'en',
          timezone: 'UTC',
          server: `http://127.0.0.1:${PORT}`,
          articlepath: '/wiki/$1',
          scriptpath: '',
        },
        statistics: { pages: 5000, articles: 1200, edits: 40000, images: 300, users: 200, activeusers: 12, admins: 3 },
      },
    });
  }
  if (list === 'recentchanges') {
    return json(res, 200, {
      query: {
        recentchanges: Array.from({ length: 8 }, (_, index) => ({
          rcid: 9000 + index,
          title: `Recent change ${index + 1}`,
          user: 'MockEditor',
          timestamp: '2026-01-01T00:00:00Z',
          comment: 'mock edit',
          type: 'edit',
          newlen: 1000,
          oldlen: 900,
        })),
      },
    });
  }
  if (list === 'allpages') {
    return json(res, 200, {
      query: {
        allpages: Array.from({ length: 50 }, (_, index) => ({ pageid: 3000 + index, title: `Mock article ${index + 1}` })),
      },
    });
  }
  if (action === 'query' && url.searchParams.get('prop') === 'revisions') {
    return json(res, 200, {
      query: {
        pages: [
          {
            pageid: 1,
            title: url.searchParams.get('titles') || 'Mock',
            revisions: [
              { revid: 501000, user: 'MockEditor', timestamp: '2026-01-01T00:00:00Z', comment: 'mock', size: 1000 },
            ],
          },
        ],
      },
    });
  }
  return json(res, 200, { batchcomplete: '' });
});

server.listen(PORT, '127.0.0.1', () => {
  console.log(
    `mock mediawiki on http://127.0.0.1:${PORT} (mode=${mode} latencyMs=${latencyMs} failRate=${failRate})`
  );
});
